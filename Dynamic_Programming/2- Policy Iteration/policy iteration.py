def argmax(q,s):
    
    # When all Qs are equal, choose one at random from the 
    # maximum actions (which are all of them initially).    
    max_q_hat_s = max(q)
    
    best_actions=[]
    for i, v in enumerate(q):
        if np.isclose(v, max_q_hat_s):
            best_actions.append(i)
    
    
    best_action = random.choice(best_actions)
    
    return best_action


#################### Policy Iteration ####################

policy_stable=False
while policy_stable== False:
    
    # Policy Evaluation
    while delta >  theta:  # k: Gauss-seidel method
        
        delta=0
        for s in [0,1,2,4,6,8,9,10,11]:
            
            v_old= v[s]
    
            v_new=0
            a = policy_pi[s]
            
            for prob, s_prime, reward, done in P[s][a]:
                v_new= v_new+ prob*(reward+v[(s_prime)])
                
            v[(s)]=v_new
            
            # Maximum change in V(s) across all states
            delta = max(delta, abs(v_old - v_new))
       
            
    # Policy Improvement
    policy_stable = True
    for s in [0,1,2,4,6,8,9,10,11]:
    
        
        old_action = policy_pi[s]
        
        q=[]
        for a in [0,1,2,3]:
            
            q_s_a=0   
            for prob, s_prime, reward, done in P[s][a]:
                q_s_a= q_s_a+ prob*(reward+v[s_prime])
                   
            q.append(q_s_a)
        
        policy_pi[s]= argmax(q,s)
    
    
        if old_action != policy_pi[s]:
            policy_stable = False


            
